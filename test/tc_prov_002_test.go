package test

import (
	"bytes"
	"encoding/json"
	"net/http"
	"net/http/httptest"
	"sync/atomic"
	"testing"

	"sourcebook/internal/api"
	"sourcebook/internal/database"
	"sourcebook/internal/llm"
	"sourcebook/internal/models"
	"sourcebook/internal/synthesis"
)

// TC-PROV-002: Dynamic Provider Mutation No-Bleed
// Scenario:
// 1. Start on openai (mockA).
// 2. Call PUT /settings with gemini (mockB).
// 3. Call /study/mindmap.
// Assert:
// - Request immediately routes to mockB.
// - Zero URL or header bleeding from mockA.
func TestTC_PROV_002_DynamicProviderMutationNoBleed(t *testing.T) {
	mockResponseA := `{
		"id": "root_a",
		"label": "Mock A OpenAI",
		"desc": "Generated by Mock A",
		"children": []
	}`
	mockResponseB := `{
		"id": "root_b",
		"label": "Mock B Gemini",
		"desc": "Generated by Mock B",
		"children": []
	}`

	var hitsA int32
	var hitsB int32
	var receivedAuthB string

	mockA := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		atomic.AddInt32(&hitsA, 1)
		w.Header().Set("Content-Type", "application/json")
		resp := map[string]interface{}{
			"choices": []map[string]interface{}{
				{"message": map[string]string{"content": mockResponseA}},
			},
		}
		json.NewEncoder(w).Encode(resp)
	}))
	defer mockA.Close()

	mockB := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		atomic.AddInt32(&hitsB, 1)
		receivedAuthB = r.Header.Get("Authorization")
		w.Header().Set("Content-Type", "application/json")
		resp := map[string]interface{}{
			"choices": []map[string]interface{}{
				{"message": map[string]string{"content": mockResponseB}},
			},
		}
		json.NewEncoder(w).Encode(resp)
	}))
	defer mockB.Close()

	// 1. Setup in-memory DB and API initialized with Mock A (OpenAI)
	db, err := database.InitDB(":memory:")
	if err != nil {
		t.Fatalf("failed to init db: %v", err)
	}
	defer db.Close()

	repo := database.NewRepository(db)
	nb, err := repo.CreateNotebook("Test Notebook", "Test Description")
	if err != nil {
		t.Fatalf("failed to create notebook: %v", err)
	}

	_ = repo.AddSource(&models.SourceRecord{
		ID:         "src-1",
		NotebookID: nb.ID,
		Title:      "Test Source",
		Content:    "Transformers and attention mechanisms.",
	})

	llmClient := llm.NewClientWithConfig("openai", mockA.URL, "gpt-4o", "token-openai-mock-a")
	synthesizer := synthesis.NewSynthesizer(llmClient)

	// Construct API with the live client and repo
	serverAPI := api.NewTestAPI(repo, llmClient, synthesizer)

	// Verify initial call hits Mock A
	mindMapReqBody, _ := json.Marshal(map[string]string{"notebook_id": nb.ID})
	req1 := httptest.NewRequest(http.MethodPost, "/api/sourcebook/v1/study/mindmap", bytes.NewReader(mindMapReqBody))
	w1 := httptest.NewRecorder()
	serverAPI.HandleMindMap(w1, req1)

	if w1.Code != http.StatusOK {
		t.Fatalf("call 1 expected 200, got %d: %s", w1.Code, w1.Body.String())
	}
	if atomic.LoadInt32(&hitsA) != 1 {
		t.Fatalf("expected 1 hit on mockA, got %d", hitsA)
	}
	if atomic.LoadInt32(&hitsB) != 0 {
		t.Fatalf("expected 0 hits on mockB, got %d", hitsB)
	}

	// 2. Call PUT /settings to dynamically mutate provider to Mock B (Gemini)
	newSettings := models.UserSettings{
		LLMProvider: "gemini",
		LLMBaseURL:  mockB.URL,
		LLMModel:    "gemini-1.5-pro",
		LLMAPIKey:   "token-gemini-mock-b",
	}
	settingsBody, _ := json.Marshal(newSettings)
	settingsReq := httptest.NewRequest(http.MethodPut, "/api/sourcebook/v1/settings", bytes.NewReader(settingsBody))
	settingsW := httptest.NewRecorder()
	serverAPI.HandleSettings(settingsW, settingsReq)

	if settingsW.Code != http.StatusOK {
		t.Fatalf("PUT /settings failed with code %d: %s", settingsW.Code, settingsW.Body.String())
	}

	// 3. Call /study/mindmap again
	req2 := httptest.NewRequest(http.MethodPost, "/api/sourcebook/v1/study/mindmap", bytes.NewReader(mindMapReqBody))
	w2 := httptest.NewRecorder()
	serverAPI.HandleMindMap(w2, req2)

	if w2.Code != http.StatusOK {
		t.Fatalf("call 2 expected 200, got %d: %s", w2.Code, w2.Body.String())
	}

	// 4. Assert: Request routed to Mock B, zero hits to Mock A, auth token matches Mock B with zero bleed
	if atomic.LoadInt32(&hitsA) != 1 {
		t.Fatalf("mockA should not receive any more requests; expected 1 hit, got %d", hitsA)
	}
	if atomic.LoadInt32(&hitsB) != 1 {
		t.Fatalf("mockB should have been hit; expected 1 hit, got %d", hitsB)
	}
	if receivedAuthB != "Bearer token-gemini-mock-b" {
		t.Fatalf("expected auth header 'Bearer token-gemini-mock-b', got '%s'", receivedAuthB)
	}

	var resp MindMapResponseHelper
	if err := json.Unmarshal(w2.Body.Bytes(), &resp); err != nil {
		t.Fatalf("failed to decode mindmap response: %v", err)
	}
	if resp.Root.ID != "root_b" || resp.Root.Label != "Mock B Gemini" {
		t.Fatalf("expected response from mock B root_b, got ID: %s, Label: %s", resp.Root.ID, resp.Root.Label)
	}
}

type MindMapResponseHelper struct {
	Root struct {
		ID    string `json:"id"`
		Label string `json:"label"`
		Desc  string `json:"desc"`
	} `json:"root"`
}
